-- Initial schema, matching the JPA entities as of PA-26..PA-29.
-- From here on, schema changes go in new versioned migrations (V2__..., V3__...);
-- Hibernate only validates the schema (ddl-auto: validate).

-- Enum columns are stored as strings and guarded by CHECK constraints.
-- Adding a value to a Java enum requires a migration that updates its constraint.

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email      VARCHAR(120) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role       VARCHAR(255) NOT NULL,
    status     VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CANDIDATE', 'RECRUITER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'PENDING_VERIFICATION', 'SUSPENDED'))
);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    token      VARCHAR(512) NOT NULL,
    revoked    BOOLEAN      NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uk_refresh_tokens_token UNIQUE (token),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);

CREATE TABLE skills (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name     VARCHAR(100) NOT NULL,
    category VARCHAR(255) NOT NULL,
    CONSTRAINT pk_skills PRIMARY KEY (id),
    CONSTRAINT uk_skills_name UNIQUE (name),
    CONSTRAINT ck_skills_category CHECK (category IN ('TECHNICAL', 'SOFT_SKILL', 'LANGUAGE', 'TOOL'))
);

CREATE TABLE companies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(255) NOT NULL,
    website    VARCHAR(255),
    industry   VARCHAR(255) NOT NULL,
    size       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_companies PRIMARY KEY (id),
    CONSTRAINT ck_companies_industry CHECK (industry IN ('TECHNOLOGY', 'HEALTHCARE', 'FINANCE', 'EDUCATION', 'RETAIL',
        'MANUFACTURING', 'CONSULTING', 'MARKETING', 'CONSTRUCTION', 'LOGISTICS', 'OTHER')),
    CONSTRAINT ck_companies_size CHECK (size IN ('STARTUP', 'SMALL', 'MEDIUM', 'LARGE'))
);
-- Case-insensitive, like the check in CompanyService, so concurrent registrations can't create "Acme" and "acme"
CREATE UNIQUE INDEX uk_companies_name_lower ON companies (LOWER(name));

CREATE TABLE candidate_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT NOT NULL,
    full_name           VARCHAR(255),
    bio                 VARCHAR(255),
    location            VARCHAR(255),
    years_of_experience INTEGER,
    phone_number        VARCHAR(255),
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_candidate_profiles PRIMARY KEY (id),
    CONSTRAINT uk_candidate_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_candidate_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE candidate_skill_levels (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    candidate_profile_id BIGINT       NOT NULL,
    skill_id             BIGINT       NOT NULL,
    level                VARCHAR(255) NOT NULL,
    CONSTRAINT pk_candidate_skill_levels PRIMARY KEY (id),
    CONSTRAINT uk_candidate_skill_levels_candidate_skill UNIQUE (candidate_profile_id, skill_id),
    CONSTRAINT fk_candidate_skill_levels_candidate FOREIGN KEY (candidate_profile_id) REFERENCES candidate_profiles (id),
    CONSTRAINT fk_candidate_skill_levels_skill FOREIGN KEY (skill_id) REFERENCES skills (id),
    CONSTRAINT ck_candidate_skill_levels_level CHECK (level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT'))
);
CREATE INDEX ix_candidate_skill_levels_skill_id ON candidate_skill_levels (skill_id);

CREATE TABLE recruiter_profiles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    job_title  VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_recruiter_profiles PRIMARY KEY (id),
    CONSTRAINT uk_recruiter_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_recruiter_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_recruiter_profiles_company FOREIGN KEY (company_id) REFERENCES companies (id)
);
CREATE INDEX ix_recruiter_profiles_company_id ON recruiter_profiles (company_id);

CREATE TABLE jobs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    recruiter_profile_id BIGINT       NOT NULL,
    title                VARCHAR(255) NOT NULL,
    description          TEXT,
    location             VARCHAR(100),
    work_mode            VARCHAR(255) NOT NULL,
    employment_type      VARCHAR(255) NOT NULL,
    status               VARCHAR(255) NOT NULL,
    created_at           TIMESTAMP(6) NOT NULL,
    updated_at           TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_jobs PRIMARY KEY (id),
    CONSTRAINT fk_jobs_recruiter_profile FOREIGN KEY (recruiter_profile_id) REFERENCES recruiter_profiles (id),
    CONSTRAINT ck_jobs_work_mode CHECK (work_mode IN ('HYBRID', 'REMOTE', 'IN_PERSON')),
    CONSTRAINT ck_jobs_employment_type CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'FREELANCE', 'INTERNSHIP')),
    CONSTRAINT ck_jobs_status CHECK (status IN ('ACTIVE', 'CLOSED', 'DRAFT'))
);
CREATE INDEX ix_jobs_recruiter_profile_id ON jobs (recruiter_profile_id);
CREATE INDEX ix_jobs_status ON jobs (status);

CREATE TABLE job_skill_requirements (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id   BIGINT  NOT NULL,
    skill_id BIGINT  NOT NULL,
    required BOOLEAN NOT NULL,
    CONSTRAINT pk_job_skill_requirements PRIMARY KEY (id),
    CONSTRAINT uk_job_skill_requirements_job_skill UNIQUE (job_id, skill_id),
    CONSTRAINT fk_job_skill_requirements_job FOREIGN KEY (job_id) REFERENCES jobs (id),
    CONSTRAINT fk_job_skill_requirements_skill FOREIGN KEY (skill_id) REFERENCES skills (id)
);
CREATE INDEX ix_job_skill_requirements_skill_id ON job_skill_requirements (skill_id);

CREATE TABLE applications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    candidate_profile_id BIGINT       NOT NULL,
    job_id               BIGINT       NOT NULL,
    status               VARCHAR(255) NOT NULL,
    created_at           TIMESTAMP(6) NOT NULL,
    updated_at           TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT uk_applications_candidate_job UNIQUE (candidate_profile_id, job_id),
    CONSTRAINT fk_applications_candidate FOREIGN KEY (candidate_profile_id) REFERENCES candidate_profiles (id),
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id),
    CONSTRAINT ck_applications_status CHECK (status IN ('APPLIED', 'REVIEWED', 'ACCEPTED', 'REJECTED'))
);
CREATE INDEX ix_applications_job_id ON applications (job_id);
